def parse_args() -> tuple[str, RunConfig]:
    parser = argparse.ArgumentParser(description=__doc__,
                                      formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("step", choices=[*STEPS, "all"])
    parser.add_argument("--first-row", type=int, default=7001,
                         help="first 1-indexed row of persuader_turns.csv (default: 7001)")
    parser.add_argument("--last-row", type=int, default=10600,
                         help="last 1-indexed row, inclusive (default: 10600)")
    parser.add_argument("--batch-size", type=int, default=200,
                         help="turns per batch (default: 200)")
    parser.add_argument("--first-batch-num", type=int, default=36,
                         help="number to assign the first batch (default: 36)")
    parser.add_argument("--out-prefix", default="claude_multilabel_7001_10600",
                         help="prefix for merged output files (default: claude_multilabel_7001_10600)")
    args = parser.parse_args()

    cfg = RunConfig(
        first_row=args.first_row,
        last_row=args.last_row,
        batch_size=args.batch_size,
        first_batch_num=args.first_batch_num,
        out_prefix=args.out_prefix,
    )
    return args.step, cfg


def main() -> None:
    step, cfg = parse_args()
    if step == "all":
        for name, fn in STEPS.items():
            print(f"\n=== [{name}] ===")
            fn(cfg)
    else:
        STEPS[step](cfg)


if __name__ == "__main__":
    main()

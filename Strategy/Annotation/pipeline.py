"""
Persuasion-Strategy Annotation Pipeline
========================================

Documents and reproduces, end-to-end, the general process used to produce
multi-label persuasion-strategy annotations on the PersuasionForGood corpus:

    persuader_turns.csv
        --> [1] SLICE into fixed-size batches (e.g. 200-turn batches over a
                target row range)
        --> [2] BUILD 5-turn dialogue context per turn (already embedded in
                the source CSV's `context` column; this step verifies /
                truncates it to the last N turns, matching the protocol)
        --> [3] ASSEMBLE the batch prompt (system prompt from prompt.md +
                the batch's JSON payload) that gets pasted into the LLM
        --> [4] ANNOTATE each batch (in production this is done by
                directly driving an LLM agent turn-by-turn/batch-by-batch
                rather than a scripted API loop -- see AnnotatorClient
                below for the pluggable seam where a real API call would
                go)
        --> [5] VALIDATE each annotated batch against the closed-world
                taxonomy and schema
        --> [6] MERGE all annotated batches into the final long-format
                JSONL/CSV and the wide one-hot CSV
        --> [7] SUMMARIZE (per-label / per-category prevalence stats) into
                SUMMARY.md

This script is a faithful *representation* of the pipeline for review
purposes, parameterized by a target row range rather than hardcoded to any
one annotation run. Step [4] does not call a live model by default -- real
runs used an LLM agent directly, one batch at a time, with a manual
smoke-test checkpoint on the first batch (see prompt.md, Section 5). It
reads already-annotated batch files when present, and only invokes
`AnnotatorClient` for batches that are missing, so that the rest of the
pipeline (slicing, context-building, prompt assembly, validation, merge,
summary) can be run and demonstrated end-to-end without re-annotating.

Usage
-----
    python pipeline.py slice            # [1]+[2] build batch_*.json from persuader_turns.csv
    python pipeline.py build-prompts    # [3] materialize the exact prompt sent per batch
    python pipeline.py annotate         # [4] annotate any batch not already in annotated_batch/
    python pipeline.py validate         # [5] schema/taxonomy check on annotated_batch/*.json
    python pipeline.py merge            # [6]+[7] merge + write SUMMARY.md
    python pipeline.py all              # run every step in order

Range configuration
--------------------
By default the pipeline targets this workspace's run (rows 7001-10600,
batches 36-53, 200 turns/batch). To point it at a different run, override
any of these via CLI flags (apply to every subcommand):

    --first-row N       first 1-indexed row of persuader_turns.csv (default 7001)
    --last-row N        last 1-indexed row, inclusive (default 10600)
    --batch-size N      turns per batch (default 200)
    --first-batch-num N number to assign the first batch (default 36)
    --out-prefix NAME   prefix for merged output files (default claude_multilabel_7001_10600)

Example: python pipeline.py all --first-row 1 --last-row 7000 --first-batch-num 1 --out-prefix claude_multilabel_1_7000
"""


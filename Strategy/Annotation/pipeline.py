# [7] SUMMARIZE -> SUMMARY.md
# ---------------------------------------------------------------------------

def write_summary(records: list[dict], cfg: RunConfig) -> None:
    n_turns = len(records)
    dialogues = {r["dialogue_id"] for r in records}
    per_dialogue = Counter(r["dialogue_id"] for r in records)
    turns_per_dialogue = list(per_dialogue.values())

    n_labels_list = [r["n_labels"] for r in records]
    mean_labels = sum(n_labels_list) / n_turns
    sorted_labels = sorted(n_labels_list)
    median_labels = sorted_labels[n_turns // 2] if n_turns % 2 else \
        (sorted_labels[n_turns // 2 - 1] + sorted_labels[n_turns // 2]) / 2
    variance = sum((x - mean_labels) ** 2 for x in n_labels_list) / n_turns
    std_dev = variance ** 0.5

    empty_set_count = sum(1 for r in records if r["n_labels"] == 0)
    labels_histogram = Counter(n_labels_list)

    cat_counts = Counter()
    strat_counts = Counter()
    for r in records:
        cat_counts.update(set(r["categories"]))
        strat_counts.update(set(r["strategies"]))

    def pct(n: int) -> str:
        return f"{100 * n / n_turns:.1f}"

    batches = cfg.batches
    lines = []
    lines.append("# annotation summary & statistics\n")
    lines.append(
        f"Multi-label persuasion-strategy annotation of rows **{cfg.first_row}-{cfg.last_row}** "
        f"of `persuader_turns.csv` ({len(ALL_STRATEGIES)} strategies / {len(TAXONOMY)} "
        f"categories). Merged from {len(batches)} batches of {cfg.batch_size} turns "
        f"(batches {batches[0][0]}-{batches[-1][0]}).\n"
    )

    lines.append("## Overview\n")
    lines.append("| Metric | Value |")
    lines.append("| --- | --- |")
    lines.append(f"| Turns | {n_turns:,} |")
    lines.append(f"| Dialogues | {len(dialogues)} |")
    lines.append(
        f"| Turns / dialogue | mean {sum(turns_per_dialogue) / len(turns_per_dialogue):.2f} "
        f"(min {min(turns_per_dialogue)}, max {max(turns_per_dialogue)}) |"
    )
    lines.append(f"| Mean labels / turn | {mean_labels:.2f} |")
    lines.append(f"| Median labels / turn | {median_labels} |")
    lines.append(f"| Std. dev. | {std_dev:.2f} |")
    lines.append(f"| Empty-set turns | {empty_set_count} ({pct(empty_set_count)}%) |")
    lines.append(f"| Max labels on a turn | {max(n_labels_list)} |")
    lines.append(f"| Distinct strategies used | {len(strat_counts)} / {len(ALL_STRATEGIES)} |")
    lines.append(f"| Distinct categories used | {len(cat_counts)} / {len(TAXONOMY)} |\n")

    lines.append("## Labels per turn\n")
    lines.append("| Labels | Turns |")
    lines.append("| --- | --- |")
    for k in range(0, max(n_labels_list) + 1):
        lines.append(f"| {k} | {labels_histogram.get(k, 0)} |")
    lines.append("")

    lines.append("## Category prevalence\n")
    lines.append("| Category | Turns | % |")
    lines.append("| --- | --- | --- |")
    for cat, n in cat_counts.most_common():
        lines.append(f"| {cat} | {n} | {pct(n)} |")
    lines.append("")

    lines.append("## Strategy prevalence (all {}) \n".format(len(ALL_STRATEGIES)))
    lines.append("| Strategy | Category | Turns | % |")
    lines.append("| --- | --- | --- | --- |")
    all_sorted = sorted(ALL_STRATEGIES, key=lambda s: strat_counts.get(s, 0), reverse=True)
    for s in all_sorted:
        n = strat_counts.get(s, 0)
        lines.append(f"| {s} | {STRATEGY_TO_CATEGORY[s]} | {n} | {pct(n)} |")

    cfg.out_summary.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"[merge] wrote {cfg.out_summary}")


def merge_and_summarize(cfg: RunConfig) -> None:
    """Step [6]+[7]: merge all annotated batches and regenerate outputs."""
    records = load_all_annotated(cfg)
    write_jsonl(records, cfg.out_jsonl)
    write_long_csv(records, cfg.out_csv)
    write_wide_csv(records, cfg.out_wide_csv)
    write_summary(records, cfg)
    print(f"[merge] {len(records)} turns -> {cfg.out_jsonl.name}, {cfg.out_csv.name}, {cfg.out_wide_csv.name}")



class RunConfig:
    """Parameters describing one annotation run over a row range of
    persuader_turns.csv. Everything downstream (batching, prompts,
    output filenames) is derived from this rather than hardcoded.
    """

    def __init__(self, first_row: int, last_row: int, batch_size: int,
                 first_batch_num: int, out_prefix: str):
        self.first_row = first_row
        self.last_row = last_row
        self.batch_size = batch_size
        self.first_batch_num = first_batch_num
        self.out_prefix = out_prefix

    @property
    def batches(self) -> list[tuple[int, int, int]]:
        """List of (batch_num, start_row, end_row), 1-indexed inclusive."""
        n_batches = (self.last_row - self.first_row + 1) // self.batch_size
        return [
            (
                self.first_batch_num + i,
                self.first_row + i * self.batch_size,
                self.first_row + i * self.batch_size + self.batch_size - 1,
            )
            for i in range(n_batches)
        ]

    @property
    def out_jsonl(self) -> Path:
        return WORKSPACE / f"{self.out_prefix}.jsonl"

    @property
    def out_csv(self) -> Path:
        return WORKSPACE / f"{self.out_prefix}.csv"

    @property
    def out_wide_csv(self) -> Path:
        return WORKSPACE / f"{self.out_prefix}_wide.csv"

    @property
    def out_summary(self) -> Path:
        return WORKSPACE / "SUMMARY.md"


def batch_filename(batch_num: int, start: int, end: int) -> str:
    return f"batch_{batch_num}_turns_{start}_{end}.json"


# ---------------------------------------------------------------------------
# [1] + [2] SLICE persuader_turns.csv into fixed-size batches, each turn
#           carrying its <=N-turn dialogue context
# ---------------------------------------------------------------------------

def truncate_context_to_last_n_turns(context: str, n: int = CONTEXT_WINDOW_TURNS) -> str:
    """Keep only the last `n` [Speaker] lines of a context blob.

    The source CSV already stores context pre-truncated to N turns; this
    is a defensive re-application of the same rule so the pipeline does
    not silently depend on upstream formatting.
    """
    if not context:
        return ""
    lines = [ln for ln in context.split("\n") if ln.strip()]
    return "\n".join(lines[-n:])


def load_source_rows() -> list[dict]:
    with open(SOURCE_CSV, encoding="utf-8", newline="") as f:
        return list(csv.DictReader(f))


def slice_into_batches(cfg: RunConfig) -> None:
    """Step [1]+[2]: recreate batch/batch_NN_turns_X_Y.json from the source CSV."""
    rows = load_source_rows()
    if cfg.last_row > len(rows):
        raise ValueError(f"persuader_turns.csv has only {len(rows)} rows, need {cfg.last_row}")

    BATCH_DIR.mkdir(parents=True, exist_ok=True)

    for batch_num, start, end in cfg.batches:
        # 1-indexed, inclusive slice -> 0-indexed python slice
        chunk = rows[start - 1:end]
        batch_turns = []
        for row in chunk:
            batch_turns.append({
                "turn_id": row["turn_id"],
                "conversation_id": row["conversation_id"],
                "dialogue_id": row["dialogue_id"],
                "turn_index": row["turn_index"],
                "persuader_turn_index": row["persuader_turn_index"],
                "n_turns_in_dialogue": row["n_turns_in_dialogue"],
                "text": row["text"],
                "context": truncate_context_to_last_n_turns(row["context"]),
                "binary_label_norm": row.get("binary_label_norm", ""),
                "modifier_norm": row.get("modifier_norm", ""),
            })

        out_path = BATCH_DIR / batch_filename(batch_num, start, end)
        with open(out_path, "w", encoding="utf-8") as f:
            json.dump(batch_turns, f, indent=2, ensure_ascii=False)
        print(f"[slice] batch {batch_num}: rows {start}-{end} -> {out_path.name} "
              f"({len(batch_turns)} turns)")


# ---------------------------------------------------------------------------
# [3] BUILD the exact prompt sent to the LLM for one batch
# ---------------------------------------------------------------------------

def extract_system_prompt() -> str:
    """Pull the fenced ```text``` block under '## 1. System Prompt' from prompt.md."""
    md = SYSTEM_PROMPT_MD.read_text(encoding="utf-8")
    match = re.search(
        r"## 1\. System Prompt.*?```text\n(.*?)\n```",
        md, re.DOTALL,
    )
    if not match:
        raise ValueError("Could not locate system prompt block in prompt.md")
    return match.group(1)


BATCH_USER_TEMPLATE = """\
Please annotate the following batch of {n} Persuader turns from the PersuasionForGood dataset according to the multi-label persuasion strategy guidelines, operational tests, and closed-world taxonomy defined in your system prompt.

For each turn, output a valid JSON object with:
- "turn_id": string
- "dialogue_id": string
- "turn_index": integer
- "strategies": list of strings (exact taxonomy names)
- "categories": list of strings (exact category names)
- "n_labels": integer (number of strategies, 0 to 6)
- "flags": list of strings (e.g. ["empty_set"] if n_labels == 0, else [])
- "note": string (concise Chain-of-Thought explaining your Removal Test and Specific-Beats-General reasoning)
- "text": string (the exact turn text)

Return your response ONLY as a single valid JSON array containing all {n} turn objects.

--- BATCH INPUT DATA ---
{payload}
"""


def build_batch_prompt(batch_num: int, start: int, end: int) -> str:
    batch_path = BATCH_DIR / batch_filename(batch_num, start, end)
    turns = json.loads(batch_path.read_text(encoding="utf-8"))
    payload = json.dumps(turns, indent=2, ensure_ascii=False)
    return BATCH_USER_TEMPLATE.format(n=len(turns), payload=payload)


def build_all_prompts(cfg: RunConfig) -> None:
    """Step [3]: materialize system + user prompt actually pasted per batch."""
    PROMPTS_DIR.mkdir(parents=True, exist_ok=True)
    system_prompt = extract_system_prompt()
    (PROMPTS_DIR / "_system_prompt.txt").write_text(system_prompt, encoding="utf-8")

    for batch_num, start, end in cfg.batches:
        user_prompt = build_batch_prompt(batch_num, start, end)
        out_path = PROMPTS_DIR / f"batch_{batch_num}_prompt.txt"
        out_path.write_text(user_prompt, encoding="utf-8")
        print(f"[build-prompts] batch {batch_num} -> {out_path.name}")


# ---------------------------------------------------------------------------
# [4] ANNOTATE: pluggable seam for the actual labeling step
# ---------------------------------------------------------------------------

class AnnotatorClient:
    """Represents "send system prompt + batch prompt to the LLM, get JSON back".

    In actual runs, annotation is performed by directly driving an LLM
    agent (Claude) turn-by-turn / batch-by-batch inside an interactive
    session -- per prompt.md Section 5's protocol: smoke-test the first
    batch, get human sign-off, then run the remaining batches in sequence.
    There is no scripted API loop.

    This class is the seam where a scripted alternative (e.g. the Claude
    Messages API) would plug in, so the rest of the pipeline is agnostic
    to how a batch actually got annotated. It intentionally raises rather
    than silently fabricating labels.
    """

    def __init__(self, system_prompt: str):
        self.system_prompt = system_prompt

    def annotate_batch(self, user_prompt: str) -> list[dict]:
        raise NotImplementedError(
            "No live model wired up. In production this batch is annotated "
            "by an LLM agent directly (see prompt.md Section 5); to automate "
            "it, call your model provider here with "
            "(system=self.system_prompt, user=user_prompt) and json.loads() "
            "the response."
        )


def annotate_missing_batches(cfg: RunConfig) -> None:
    """Step [4]: annotate any batch whose annotated_batch/*.json is missing."""
    ANNOTATED_DIR.mkdir(parents=True, exist_ok=True)
    system_prompt = extract_system_prompt()
    client = AnnotatorClient(system_prompt)

    for batch_num, start, end in cfg.batches:
        out_path = ANNOTATED_DIR / f"batch_{batch_num}_annotated.json"
        if out_path.exists():
            print(f"[annotate] batch {batch_num}: already annotated, skipping")
            continue

        print(f"[annotate] batch {batch_num}: not yet annotated -- invoking AnnotatorClient")
        user_prompt = build_batch_prompt(batch_num, start, end)
        annotated = client.annotate_batch(user_prompt)
        out_path.write_text(json.dumps(annotated, indent=2, ensure_ascii=False), encoding="utf-8")


# ---------------------------------------------------------------------------
# [5] VALIDATE annotated batches against schema + closed-world taxonomy
# ---------------------------------------------------------------------------

REQUIRED_FIELDS = {
    "turn_id", "dialogue_id", "turn_index", "strategies",
    "categories", "n_labels", "flags", "note", "text",
}


def validate_record(rec: dict) -> list[str]:
    errors = []
    missing = REQUIRED_FIELDS - rec.keys()
    if missing:
        errors.append(f"missing fields {missing}")
        return errors  # can't check further without the fields

    for strat in rec["strategies"]:
        if strat not in STRATEGY_TO_CATEGORY:
            errors.append(f"unknown strategy '{strat}' (not in closed-world taxonomy)")

    expected_categories = {STRATEGY_TO_CATEGORY[s] for s in rec["strategies"] if s in STRATEGY_TO_CATEGORY}
    if set(rec["categories"]) != expected_categories:
        errors.append(
            f"categories {rec['categories']} do not match strategies-derived "
            f"categories {sorted(expected_categories)}"
        )

    if rec["n_labels"] != len(rec["strategies"]):
        errors.append(f"n_labels={rec['n_labels']} != len(strategies)={len(rec['strategies'])}")

    if rec["n_labels"] > MAX_LABELS:
        errors.append(f"n_labels={rec['n_labels']} exceeds schema cap of {MAX_LABELS}")

    if rec["n_labels"] == 0 and "empty_set" not in rec["flags"]:
        errors.append("n_labels == 0 but flags missing 'empty_set'")

    return errors


def resolve_annotated_path(batch_num: int) -> Path:
    """Locate the annotated file for a batch, tolerating known filename
    variants (e.g. an extra underscore) rather than failing the whole run.
    """
    canonical = ANNOTATED_DIR / f"batch_{batch_num}_annotated.json"
    if canonical.exists():
        return canonical
    variant = ANNOTATED_DIR / f"batch_{batch_num}__annotated.json"
    if variant.exists():
        print(f"[merge] NOTE: batch {batch_num} uses non-standard filename "
              f"'{variant.name}' (expected '{canonical.name}')")
        return variant
    raise FileNotFoundError(f"No annotated file found for batch {batch_num} "
                             f"(looked for {canonical.name} and {variant.name})")


def validate_all(cfg: RunConfig) -> bool:
    """Step [5]: validate every annotated_batch/*.json file in this run. Returns True if clean."""
    ok = True
    off_taxonomy = Counter()
    for batch_num, start, end in cfg.batches:
        try:
            path = resolve_annotated_path(batch_num)
        except FileNotFoundError:
            print(f"[validate] batch {batch_num}: MISSING")
            ok = False
            continue

        records = json.loads(path.read_text(encoding="utf-8"))
        expected_n = end - start + 1
        if len(records) != expected_n:
            print(f"[validate] batch {batch_num}: expected {expected_n} turns, found {len(records)}")
            ok = False

        batch_errors = 0
        for rec in records:
            errs = validate_record(rec)
            if errs:
                batch_errors += 1
                for e in errs:
                    print(f"[validate] batch {batch_num} turn {rec.get('turn_id', '?')}: {e}")
            off_taxonomy.update(s for s in rec.get("strategies", []) if s not in STRATEGY_TO_CATEGORY)
        status = "OK" if batch_errors == 0 and len(records) == expected_n else f"{batch_errors} record error(s)"
        print(f"[validate] batch {batch_num}: {status}")
        ok = ok and batch_errors == 0

    if off_taxonomy:
        print(f"\n[validate] off-taxonomy strategy labels found across all batches (known QA issue):")
        for label, n in off_taxonomy.most_common():
            print(f"    '{label}': {n} turn(s)")
        ok = False

    return ok


# ---------------------------------------------------------------------------
# [6] MERGE annotated batches -> long JSONL/CSV + wide one-hot CSV
# ---------------------------------------------------------------------------

def load_all_annotated(cfg: RunConfig) -> list[dict]:
    records = []
    for batch_num, start, end in cfg.batches:
        path = resolve_annotated_path(batch_num)
        records.extend(json.loads(path.read_text(encoding="utf-8")))
    return records


def write_jsonl(records: list[dict], out_path: Path) -> None:
    with open(out_path, "w", encoding="utf-8") as f:
        for rec in records:
            f.write(json.dumps(rec, ensure_ascii=False) + "\n")


def write_long_csv(records: list[dict], out_path: Path) -> None:
    fields = ["turn_id", "dialogue_id", "turn_index", "model", "model_id",
              "strategies", "categories", "n_labels", "flags", "note", "text"]
    with open(out_path, "w", encoding="utf-8", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=fields)
        writer.writeheader()
        for rec in records:
            writer.writerow({
                "turn_id": rec["turn_id"],
                "dialogue_id": rec["dialogue_id"],
                "turn_index": rec["turn_index"],
                "model": "claude",
                "model_id": "claude-opus-5 (manual annotation, not a model run)",
                "strategies": "|".join(rec["strategies"]),
                "categories": "|".join(rec["categories"]),
                "n_labels": rec["n_labels"],
                "flags": "|".join(rec["flags"]),
                "note": rec["note"],
                "text": rec["text"],
            })


def write_wide_csv(records: list[dict], out_path: Path) -> None:
    cat_cols = ["cat_" + c.replace(" ", "_") for c in TAXONOMY.keys()]
    strat_cols = ["has_" + s for s in ALL_STRATEGIES]
    fields = ["turn_id", "dialogue_id"] + strat_cols + cat_cols

    with open(out_path, "w", encoding="utf-8", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=fields)
        writer.writeheader()
        for rec in records:
            row = {"turn_id": rec["turn_id"], "dialogue_id": rec["dialogue_id"]}
            strat_set = set(rec["strategies"])
            cat_set = set(rec["categories"])
            for s in ALL_STRATEGIES:
                row["has_" + s] = int(s in strat_set)
            for c in TAXONOMY.keys():
                row["cat_" + c.replace(" ", "_")] = int(c in cat_set)
            writer.writerow(row)


